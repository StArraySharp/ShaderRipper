using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using ShaderRipper.Data;

namespace ShaderRipper.Resolve
{
    /// <summary>
    /// Per-shader <c>$Globals</c> layout tables (<c>Resources/data/tmp_layouts.json</c>).
    ///
    /// TMP shaders ship their <c>$Globals</c> member table stripped to zero entries:
    /// the parameter blob records no names, the asset reflection is empty, and the
    /// rows are therefore bare.  The layout itself is still determined -- it is
    /// whatever fxc produces from the declaration order plus HLSL's packing rules,
    /// and the declaration order lives in Unity's own CGIncludes.
    ///
    /// The tables are generated by compiling those includes and reading the RDEF
    /// back.  <c>CBUFFER_START</c> only expands to <c>cbuffer</c> under
    /// <c>SHADER_API_D3D11</c>; without that define the resulting <c>$Globals</c>
    /// swallows the PerCamera/PerDraw globals and matches nothing.
    ///
    /// One shader may have several layouts (one per pass), so the table is an array
    /// rather than a per-file dictionary; selection is by declaration row count, then
    /// by how many member names overlap the program's name table, then by requiring
    /// the table to cover every row the program reads.  If any of those fails the
    /// whole table is dropped and the rows stay numeric.
    /// </summary>
    internal static class TmpLayouts
    {
        public sealed class Member
        {
            public string Name;
            public int Offset;
            public string Type;
        }

        public sealed class Layout
        {
            public string Source;
            public int Bytes;
            public int Rows;
            public List<Member> Members = new();
        }

        private static readonly List<Layout> _all = new();

        /// <summary>The one table file, embedded as <c>Resources/data/tmp_layouts.json</c>.</summary>
        private const string FileName = "tmp_layouts.json";

        public static int Count => _all.Count;
        public static string ResolvedDir { get; private set; }

        /// <summary>On by default: every layout is checked against the <c>dcl</c> row
        /// count and the name table.</summary>
        public static bool Enabled = true;

        public static int Load(string dir = null)
        {
            _all.Clear();
            string path = ResolveFile(dir);
            if (path == null) return -1;
            ResolvedDir = path;

            try
            {
                using var doc = System.Text.Json.JsonDocument.Parse(File.ReadAllText(path));
                if (!doc.RootElement.TryGetProperty("layouts", out var arr) ||
                    arr.ValueKind != System.Text.Json.JsonValueKind.Array)
                    return -1;

                foreach (var e in arr.EnumerateArray())
                {
                    var lay = new Layout
                    {
                        Source = e.TryGetProperty("source", out var src) ? src.GetString() ?? "" : "",
                        Bytes = e.TryGetProperty("bytes", out var b) ? b.GetInt32() : 0,
                        Rows = e.TryGetProperty("rows", out var r) ? r.GetInt32() : 0,
                    };
                    if (e.TryGetProperty("members", out var ms) &&
                        ms.ValueKind == System.Text.Json.JsonValueKind.Array)
                        foreach (var m in ms.EnumerateArray())
                            lay.Members.Add(new Member
                            {
                                Type = m.TryGetProperty("type", out var t) ? t.GetString() ?? "" : "",
                                Name = m.TryGetProperty("name", out var n) ? n.GetString() ?? "" : "",
                                Offset = m.TryGetProperty("offset", out var o) ? o.GetInt32() : 0,
                            });
                    if (lay.Rows > 0 && lay.Members.Count > 0) _all.Add(lay);
                }
            }
            catch { return -1; }
            return _all.Count;
        }

        private static int Comps(string type) => type switch
        {
            "float" => 1, "float2" => 2, "float3" => 3, "float4" => 4, _ => 0,
        };

        private static int Rows(string type) => type switch
        {
            "float2x2" => 2, "float3x3" => 3, "float4x4" => 4, _ => 0,
        };

        /// <summary>
        /// Pick a layout for a <c>$Globals</c> program and expand it into
        /// (row, col) -> (expression, component count); null when nothing is credible.
        /// </summary>
        public static Dictionary<(int row, int col), (string expr, int comps)> Match(
            int declaredRows, ICollection<string> nameTable, SortedSet<int> readRows, out Layout chosen,
            IReadOnlyDictionary<string, int> anchors = null)
        {
            chosen = null;
            if (!Enabled || _all.Count == 0) return null;
            if (declaredRows <= 0 || readRows == null || readRows.Count == 0) return null;

            var known = new HashSet<string>(nameTable ?? Array.Empty<string>(), StringComparer.Ordinal);

            Layout best = null;
            int bestScore = 0;
            foreach (var lay in _all)
            {
                if (lay.Rows < declaredRows || lay.Members.Count == 0) continue;

                var cov = Coverage(lay);
                if (readRows.Any(r => !cov.Contains(r))) continue;

                int overlap = lay.Members.Count(m => known.Contains(m.Name));
                int agree = anchors == null ? 0
                    : anchors.Count(a => lay.Members.Any(m => m.Name == a.Key && m.Offset == a.Value));
                bool accepted = agree >= 3 || overlap >= 4;
                if (!accepted) continue;

                int score = agree * 10 + overlap + (lay.Rows == declaredRows ? 1 : 0);
                if (score > bestScore ||
                    (score == bestScore && best != null && lay.Bytes < best.Bytes))
                {
                    best = lay;
                    bestScore = score;
                }
            }
            if (best == null) return null;
            chosen = best;
            return BuildMap(best);
        }

        /// <summary>
        /// Expand a layout a sibling sub-program already confirmed.
        ///
        /// The fragment program a surface shader generates often has no parameter blob
        /// at all and a name table down to <c>_LightColor0</c>/<c>_SpecColor</c>, which
        /// is not enough evidence on its own -- but the vertex program of the same
        /// shader already confirmed the layout, and a <c>$Globals</c> layout follows
        /// declaration order, so equal sizes mean an equal layout.
        /// </summary>
        public static Dictionary<(int row, int col), (string expr, int comps)> MapFrom(
            Layout lay, int declaredRows, SortedSet<int> readRows)
        {
            if (lay == null || readRows == null || readRows.Count == 0) return null;
            if (lay.Rows < declaredRows) return null;
            var cov = Coverage(lay);
            if (readRows.Any(r => !cov.Contains(r))) return null;
            return BuildMap(lay);
        }

        private static Dictionary<(int, int), (string, int)> BuildMap(Layout best)
        {
            var map = new Dictionary<(int, int), (string, int)>();
            foreach (var m in best.Members)
            {
                int mrows = Rows(m.Type);
                if (mrows > 0)
                {
                    int r0 = m.Offset / 16;
                    if (m.Offset % 16 != 0) continue;
                    for (int k = 0; k < mrows; k++)
                    {
                        map[(r0 + k, 0)] = ($"{m.Name}[{k}]", 4);
                    }
                    continue;
                }

                int comps = Comps(m.Type);
                if (comps == 0) continue;
                if (m.Offset % 4 != 0) continue;
                int row = m.Offset / 16, col = (m.Offset % 16) / 4;
                if (col + comps > 4) continue;

                if (comps == 4 && col == 0) map[(row, 0)] = (m.Name, 4);
                else
                    for (int k = 0; k < comps; k++)
                        map[(row, col + k)] = (m.Name, comps);
            }

            return map;
        }

        /// <summary>Which 16-byte rows this layout covers.</summary>
        private static HashSet<int> Coverage(Layout lay)
        {
            var cov = new HashSet<int>();
            foreach (var m in lay.Members)
            {
                int n = Rows(m.Type);
                if (n > 0)
                    for (int k = 0; k < n; k++) cov.Add(m.Offset / 16 + k);
                else if (Comps(m.Type) > 0)
                    cov.Add(m.Offset / 16);
            }
            return cov;
        }

        /// <summary>Why <see cref="Match"/> returned null (diagnostics only).</summary>
        public static string DebugWhy(int rows, ICollection<string> nameTable, SortedSet<int> readRows)
        {
            var same = _all.Where(l => l.Rows >= rows).ToList();
            if (same.Count == 0) return $"no layout with >= {rows} rows";
            string s = string.Join(" | ", same.Select(l =>
            {
                int sc = l.Members.Count(m => nameTable.Contains(m.Name));
                var cov = Coverage(l);
                var miss = readRows.Where(r => !cov.Contains(r)).ToList();
                return $"{l.Source}:{l.Rows}r,overlap={sc},uncovered=[{string.Join(",", miss)}]";
            }));
            return s;
        }

        /// <summary>
        /// Locate the layout table.  <paramref name="dir"/> may be the JSON file
        /// itself or a directory holding it; with neither, the embedded copy is
        /// unpacked to the temp directory.
        /// </summary>
        private static string ResolveFile(string dir)
        {
            if (!string.IsNullOrWhiteSpace(dir))
            {
                if (File.Exists(dir)) return Path.GetFullPath(dir);
                if (Directory.Exists(dir))
                {
                    string inDir = Path.Combine(dir, FileName);
                    if (File.Exists(inDir)) return Path.GetFullPath(inDir);
                }
            }
            return Paths.Find(Path.Combine("data", FileName));
        }
    }
}
